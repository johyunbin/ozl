def key(s: str) -> str:
    """공백과 문장부호를 뺀 소문자(찾기와 겹침 세기의 열쇠)."""
    return re.sub(r"[^\w가-힣]+", "", s or "").lower()


def person(raw: str) -> tuple[str, str]:
    """(열쇠, 보이는 이름). 직함을 떼고, 외래어 표기를 맞추고, 성만 적은 유명인은 전체 이름으로."""
    toks = [t for t in re.split(r"\s+", (raw or "").strip()) if t and t.lower() not in TITLES]
    toks = [t for t in toks if not re.fullmatch(r"[A-Za-z]\.?", t)]  # 영문 가운데 글자(F.)
    toks = [PERSON_TOKEN_ALIAS_V3.get(t, t) for t in toks]
    if toks:
        toks[-1] = _TITLE_TAIL.sub("", toks[-1]) or toks[-1]
    disp = " ".join(toks).strip() or (raw or "").strip()
    disp = PERSON_FULL.get(key(disp), disp)
    return key(disp), disp


def _org_split(name: str) -> tuple[str, str]:
    head, _, rest = name.strip().partition(" ")
    if rest and head in COUNTRY_PREFIX:
        return ("미국" if head == "미" else "한국" if head == "대한민국" else head), rest
    return "", name.strip()


def org(raw: str) -> tuple[str, str]:
    """(열쇠, 보이는 이름). 앞의 나라를 '미국' 꼴로, 회사 표시((주) 등)를 떼고, 사전에 있는 다른 표기를 맞춘다."""
    country, rest = _org_split(raw or "")
    core = _ORG_MARK.sub("", rest).strip()
    k = key(country + core).replace("대한민국", "한국")
    k_bare = key(core).replace("대한민국", "한국")
    if k in ORG_CANON:
        disp = ORG_CANON[k]
    elif not country and k_bare in ORG_CANON:
        disp = ORG_CANON[k_bare]
    elif country and k_bare in ORG_CANON and ORG_CANON[k_bare].startswith(country + " "):
        disp = ORG_CANON[k_bare]
    else:
        disp = (country + " " + core).strip() if country else core
    return key(disp).replace("대한민국", "한국"), disp


def country(raw: str) -> tuple[str, str]:
    s = (raw or "").strip()
    disp = COUNTRY_ALIAS.get(s.lower(), s)
    return key(disp), disp


def canon(kind: str, raw: str) -> tuple[str, str]:
    return {"person": person, "org": org, "country": country}[kind](raw)
